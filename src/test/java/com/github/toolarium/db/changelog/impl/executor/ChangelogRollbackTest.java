package com.github.toolarium.db.changelog.impl.executor;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.github.toolarium.db.changelog.ChangelogRunnerBuilder;
import com.github.toolarium.db.changelog.IChangelogRunner;
import com.github.toolarium.db.changelog.exception.ChangelogException;
import com.github.toolarium.db.changelog.impl.ChangelogRunnerImpl;
import com.github.toolarium.db.changelog.model.Changelog;
import com.github.toolarium.db.changelog.model.ChangelogChangeSet;
import com.github.toolarium.db.changelog.model.ChangelogChangeSetIdentity;
import com.github.toolarium.db.changelog.model.IChangelogEntry;
import com.github.toolarium.db.changelog.model.sql.SqlChangelogEntry;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.Statement;
import java.time.Instant;
import java.util.Arrays;
import java.util.Collections;
import java.util.List;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;


/**
 * Tests for rollback operations.
 *
 * @author patrick
 */
public class ChangelogRollbackTest {
    private static final String FILEPATH = "test.db.yaml";
    private static final String AUTHOR = "dev";
    private static final String CS_1 = "cs-1";
    private static final String CS_2 = "cs-2";
    private JdbcDataSource dataSource;


    /**
     * Set up.
     */
    @BeforeEach
    void setUp() {
        dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:rollback_" + System.nanoTime() + ";DB_CLOSE_DELAY=-1");
        dataSource.setUser("sa");
        dataSource.setPassword("");
    }


    /**
     * Test rollback by count with manual rollback entries.
     *
     * @throws Exception on error
     */
    @Test
    void testRollbackByCount() throws Exception {
        IChangelogRunner runner = createRunner(
                changeSetWithRollback(CS_1,
                        "CREATE TABLE rb_test (id INT PRIMARY KEY)",
                        "DROP TABLE rb_test"),
                changeSetWithRollback(CS_2,
                        "INSERT INTO rb_test (id) VALUES (1)",
                        "DELETE FROM rb_test WHERE id = 1"));

        runner.update();
        assertEquals(2, runner.history().size());

        runner.rollback(1);
        assertEquals(1, runner.history().size());
        assertEquals(CS_1, runner.history().get(0).getId());
    }


    /**
     * Test rollback by tag.
     *
     * @throws Exception on error
     */
    @Test
    void testRollbackByTag() throws Exception {
        IChangelogRunner runner = createRunner(
                changeSetWithRollback(CS_1,
                        "CREATE TABLE tag_test (id INT PRIMARY KEY)",
                        "DROP TABLE tag_test"),
                changeSetWithRollback(CS_2,
                        "ALTER TABLE tag_test ADD COLUMN name VARCHAR(50)",
                        "ALTER TABLE tag_test DROP COLUMN name"));

        runner.update(1);
        runner.tag("v1.0");
        runner.update();

        assertEquals(2, runner.history().size());

        runner.rollback("v1.0");
        assertEquals(1, runner.history().size());
        assertEquals(CS_1, runner.history().get(0).getId());
    }


    /**
     * Test rollback by date.
     *
     * @throws Exception on error
     */
    @Test
    void testRollbackByDate() throws Exception {
        final Instant before = Instant.now();
        Thread.sleep(50);

        IChangelogRunner runner = createRunner(
                changeSetWithRollback(CS_1,
                        "CREATE TABLE date_test (id INT PRIMARY KEY)",
                        "DROP TABLE date_test"));
        runner.update();

        assertEquals(1, runner.history().size());

        runner.rollback(before);
        assertEquals(0, runner.history().size());
    }


    /**
     * Test rollback with auto-rollback (raw SQL Level 1).
     *
     * @throws Exception on error
     */
    @Test
    void testRollbackAutoGeneratedFromSql() throws Exception {
        IChangelogRunner runner = createRunner(
                changeSet(CS_1, "CREATE TABLE auto_rb (id INT PRIMARY KEY)"));

        runner.update();
        assertEquals(1, runner.history().size());

        // Level 1 SQL rollback should generate DROP TABLE
        runner.rollback(1);
        assertEquals(0, runner.history().size());
    }


    /**
     * Test generateRollbackSql dry-run.
     *
     * @throws Exception on error
     */
    @Test
    void testGenerateRollbackSql() throws Exception {
        IChangelogRunner runner = createRunner(
                changeSetWithRollback(CS_1,
                        "CREATE TABLE gen_rb (id INT PRIMARY KEY)",
                        "DROP TABLE gen_rb"));

        runner.update();

        List<String> rollbackSql = runner.generateRollbackSql(1);
        assertFalse(rollbackSql.isEmpty());
        assertTrue(rollbackSql.get(0).contains("DROP TABLE"));

        // Dry-run should not change history
        assertEquals(1, runner.history().size());
    }


    /**
     * Test rollback with unknown tag throws.
     *
     * @throws Exception on error
     */
    @Test
    void testRollbackUnknownTagThrows() throws Exception {
        IChangelogRunner runner = createRunner(
                changeSet(CS_1, "CREATE TABLE unknown_tag (id INT PRIMARY KEY)"));
        runner.update();

        assertThrows(ChangelogException.class, () -> runner.rollback("nonexistent"));
    }


    /**
     * Test rollback removes table from database.
     *
     * @throws Exception on error
     */
    @Test
    void testRollbackRemovesTable() throws Exception {
        IChangelogRunner runner = createRunner(
                changeSetWithRollback(CS_1,
                        "CREATE TABLE remove_test (id INT PRIMARY KEY)",
                        "DROP TABLE remove_test"));

        runner.update();

        // Table exists
        try (Connection conn = dataSource.getConnection();
             Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery("SELECT COUNT(*) FROM remove_test")) {
            assertTrue(rs.next());
        }

        runner.rollback(1);

        // Table should be gone
        try (Connection conn = dataSource.getConnection();
             Statement stmt = conn.createStatement()) {
            assertThrows(Exception.class, () -> stmt.executeQuery("SELECT COUNT(*) FROM remove_test"));
        }
    }


    /**
     * Test rollback with structured DDL auto-rollback (CreateTable auto-generates DropTable).
     *
     * @throws Exception on error
     */
    @Test
    void testRollbackStructuredDdlAutoRollback() throws Exception {
        com.github.toolarium.db.changelog.model.column.ChangelogColumnDefinition col =
                new com.github.toolarium.db.changelog.model.column.ChangelogColumnDefinition("id", "INT");
        col.setPrimaryKey(true).setNullable(false);

        com.github.toolarium.db.changelog.model.table.CreateTableChangelogEntry createTable =
                new com.github.toolarium.db.changelog.model.table.CreateTableChangelogEntry("auto_ddl_rb",
                        Collections.singletonList(col));

        ChangelogChangeSetIdentity identity = new ChangelogChangeSetIdentity("ddl-auto", AUTHOR, FILEPATH);
        ChangelogChangeSet cs = new ChangelogChangeSet(identity, Collections.singletonList(createTable));

        IChangelogRunner runner = createRunner(cs);
        runner.update();
        assertEquals(1, runner.history().size());

        // Auto-rollback: CreateTable -> DropTable
        runner.rollback(1);
        assertEquals(0, runner.history().size());

        // Table should be gone
        try (Connection conn = dataSource.getConnection();
             Statement stmt = conn.createStatement()) {
            assertThrows(Exception.class, () -> stmt.executeQuery("SELECT COUNT(*) FROM auto_ddl_rb"));
        }
    }


    /**
     * Create a runner with programmatic changesets.
     *
     * @param changeSets the changesets
     * @return the runner
     */
    private IChangelogRunner createRunner(ChangelogChangeSet... changeSets) {
        ChangelogRunnerImpl runner = (ChangelogRunnerImpl) ChangelogRunnerBuilder.builder()
                .dataSource(dataSource).build();
        runner.setChangelog(new Changelog(FILEPATH, Arrays.asList(changeSets)));
        return runner;
    }


    /**
     * Create a changeset with no rollback.
     *
     * @param id the id
     * @param sql the SQL
     * @return the changeset
     */
    private ChangelogChangeSet changeSet(String id, String sql) {
        ChangelogChangeSetIdentity identity = new ChangelogChangeSetIdentity(id, AUTHOR, FILEPATH);
        return new ChangelogChangeSet(identity, Collections.singletonList(new SqlChangelogEntry(sql)));
    }


    /**
     * Create a changeset with manual rollback.
     *
     * @param id the id
     * @param sql the forward SQL
     * @param rollbackSql the rollback SQL
     * @return the changeset
     */
    private ChangelogChangeSet changeSetWithRollback(String id, String sql, String rollbackSql) {
        ChangelogChangeSetIdentity identity = new ChangelogChangeSetIdentity(id, AUTHOR, FILEPATH);
        List<IChangelogEntry> entries = Collections.singletonList(new SqlChangelogEntry(sql));
        List<IChangelogEntry> rollback = Collections.singletonList(new SqlChangelogEntry(rollbackSql));
        return new ChangelogChangeSet(identity, entries, rollback, null,
                false, false, true, true, Collections.emptyList(), Collections.emptyList(), null);
    }


    /**
     * Create a runner with FAIL rollback policy.
     *
     * @param changeSets the changesets
     * @return the runner
     */
    private IChangelogRunner createRunnerWithFailPolicy(ChangelogChangeSet... changeSets) {
        ChangelogRunnerImpl runner = (ChangelogRunnerImpl) ChangelogRunnerBuilder.builder()
                .dataSource(dataSource)
                .rollbackPolicy(com.github.toolarium.db.changelog.config.ChangelogRollbackPolicy.FAIL)
                .build();
        runner.setChangelog(new Changelog(FILEPATH, Arrays.asList(changeSets)));
        return runner;
    }


    /**
     * Test rollback with FAIL policy throws when no rollback is available.
     *
     * @throws Exception on error
     */
    @Test
    void testRollbackFailPolicyThrowsOnMissing() throws Exception {
        // Use INSERT which has no auto-rollback and no manual rollback
        IChangelogRunner setupRunner = createRunnerWithFailPolicy(
                changeSetWithRollback("setup-fp", "CREATE TABLE fail_policy_test (id INT PRIMARY KEY)", "DROP TABLE fail_policy_test")
        );
        setupRunner.update();

        // Now add a second changeset with no rollback possible
        IChangelogRunner runner = createRunnerWithFailPolicy(
                changeSetWithRollback("setup-fp", "CREATE TABLE fail_policy_test (id INT PRIMARY KEY)", "DROP TABLE fail_policy_test"),
                changeSet("no-rb-fp", "INSERT INTO fail_policy_test (id) VALUES (1)")
        );
        runner.update();

        // Rollback should fail because INSERT has no rollback and policy is FAIL
        assertThrows(ChangelogException.class, () -> runner.rollback(1));
    }


    /**
     * Test resilient rollback continues on partial failure and reports errors.
     *
     * @throws Exception on error
     */
    @Test
    void testResilientRollbackContinuesOnFailure() throws Exception {
        // Two changesets: first has rollback that will fail, second has valid rollback
        IChangelogRunner runner = createRunner(
                changeSetWithRollback("resilient-1",
                        "CREATE TABLE resilient_t1 (id INT PRIMARY KEY)",
                        "DROP TABLE resilient_t1"),
                changeSetWithRollback("resilient-2",
                        "CREATE TABLE resilient_t2 (id INT PRIMARY KEY)",
                        "DROP TABLE nonexistent_table_xyz")  // this rollback SQL will fail
        );

        runner.update();

        // Rollback should complete (resilient) but throw with failure summary
        assertThrows(ChangelogException.class, () -> runner.rollback(2));
    }
}
